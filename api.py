import os
from typing import Annotated

import joblib
import numpy as np
import pandas as pd
import shap
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field, field_validator

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
BASE = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE, "results", "XGBoost.joblib")
PREPROCESSOR_PATH = os.path.join(BASE, "data", "processed", "preprocessor.joblib")

FEATURE_NAMES = [
    "Pregnancies", "Glucose", "BloodPressure", "SkinThickness",
    "Insulin", "BMI", "DiabetesPedigreeFunction", "Age",
]

OPTIMAL_THRESHOLD = 0.38

# Load once at startup
model = joblib.load(MODEL_PATH)
preprocessor = joblib.load(PREPROCESSOR_PATH)
_explainer = shap.TreeExplainer(model)

# ---------------------------------------------------------------------------
# Pydantic schemas
# ---------------------------------------------------------------------------
class PatientInput(BaseModel):
    Pregnancies: Annotated[int, Field(ge=0, le=20, description="Number of pregnancies")]
    Glucose: Annotated[float, Field(gt=0, le=250, description="Plasma glucose (mg/dL)")]
    BloodPressure: Annotated[float, Field(gt=0, le=150, description="Diastolic BP (mm Hg)")]
    SkinThickness: Annotated[float, Field(ge=0, le=99, description="Triceps skin fold (mm)")]
    Insulin: Annotated[float, Field(ge=0, le=900, description="2-hr serum insulin (µU/mL)")]
    BMI: Annotated[float, Field(gt=0, le=70, description="Body Mass Index (kg/m²)")]
    DiabetesPedigreeFunction: Annotated[float, Field(ge=0.0, le=3.0)]
    Age: Annotated[int, Field(ge=10, le=120, description="Age in years")]

    @field_validator("Glucose")
    @classmethod
    def glucose_not_zero(cls, v):
        if v == 0:
            raise ValueError("Glucose cannot be 0 — biologically impossible")
        return v

    @field_validator("BMI")
    @classmethod
    def bmi_not_zero(cls, v):
        if v == 0:
            raise ValueError("BMI cannot be 0 — biologically impossible")
        return v


class PredictionResponse(BaseModel):
    probability: float
    prediction: int
    risk_tier: str
    clinical_action: str
    top_shap_features: list[dict]
    threshold_used: float
    model: str
    version: str


class HealthResponse(BaseModel):
    status: str
    model: str
    version: str


# ---------------------------------------------------------------------------
# Risk tier helper
# ---------------------------------------------------------------------------
def _risk_tier(prob: float) -> tuple[str, str]:
    if prob < 0.25:
        return "Low Risk", "Routine monitoring. Maintain healthy lifestyle and annual check-up."
    elif prob < 0.50:
        return "Moderate Risk", "Lifestyle changes recommended. Consider HbA1c test within 6 months."
    elif prob < 0.75:
        return "High Risk", "GP referral recommended. Request fasting glucose and HbA1c within 4 weeks."
    else:
        return "Critical Risk", "Immediate clinical evaluation recommended. Do not delay."


# ---------------------------------------------------------------------------
# FastAPI app
# ---------------------------------------------------------------------------
app = FastAPI(
    title="Diabetes Risk Prediction API",
    description=(
        "Phase 2 REST API for diabetes risk prediction using XGBoost + SHAP. "
        "BTP Project — Priya Sharma, IIT-Guwahati 2025."
    ),
    version="2.0.0",
)


@app.get("/health", response_model=HealthResponse, tags=["System"])
def health():
    """Liveness check — returns model name and version."""
    return HealthResponse(status="ok", model="XGBoost", version="2.0.0")


@app.post("/predict", response_model=PredictionResponse, tags=["Prediction"])
def predict(patient: PatientInput):
    """
    Predict diabetes risk for a single patient.

    Returns probability, risk tier, clinical action, and top SHAP features.
    """
    try:
        df = pd.DataFrame([patient.model_dump()])[FEATURE_NAMES]
        X_scaled = preprocessor.transform(df)
        prob = float(model.predict_proba(X_scaled)[0, 1])
        pred = int(prob >= OPTIMAL_THRESHOLD)
        tier, action = _risk_tier(prob)

        sv = _explainer(X_scaled)
        if sv.values.ndim == 3:
            shap_vals = sv.values[0, :, 1]
        else:
            shap_vals = sv.values[0]

        top_shap = sorted(
            [
                {"feature": name, "shap_value": round(float(val), 5)}
                for name, val in zip(FEATURE_NAMES, shap_vals)
            ],
            key=lambda x: abs(x["shap_value"]),
            reverse=True,
        )[:3]

        return PredictionResponse(
            probability=round(prob, 4),
            prediction=pred,
            risk_tier=tier,
            clinical_action=action,
            top_shap_features=top_shap,
            threshold_used=OPTIMAL_THRESHOLD,
            model="XGBoost",
            version="2.0.0",
        )
    except Exception as ex:
        raise HTTPException(status_code=500, detail=str(ex))
